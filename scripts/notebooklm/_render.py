CONFIG_FILES = [
    "package.json", "next.config.js", "next.config.mjs", "next.config.ts", "tsconfig.json",
    ".eslintrc.json", "eslint.config.mjs", "prettier.config.js", ".prettierignore",
    "postcss.config.mjs", "vercel.json", ".mcp.json", ".claude/settings.json",
]


def doc_50(c) -> str:
    pkg = c["package"]
    s = header("Build, Deploy and Tooling Config",
               "npm scripts, framework config, CI, deploy target and Claude Code tooling.", c["now"])
    s += "## npm scripts\n\n| Script | Command |\n|---|---|\n"
    for k, v in sorted((pkg.get("scripts") or {}).items()):
        s += f"| `{k}` | `{v}` |\n"
    s += "\n"
    for key in ("homepage", "engines"):
        if key in pkg:
            s += f"- **`{key}`:** `{pkg[key]}`\n"
    s += "\n## Config files\n\n"
    for f in CONFIG_FILES:
        if f == "package.json" or f not in c["texts"]:
            continue
        body = c["texts"][f].rstrip()
        lang = "json" if f.endswith(".json") else ("js" if f.endswith((".js", ".mjs", ".ts")) else "")
        s += f"### `{f}`\n\n```{lang}\n{body}\n```\n\n"

    wf = [f for f in c["files"] if f.startswith(".github/workflows/")]
    s += "## CI workflows\n\n" + ("".join(f"- `{f}`\n" for f in wf) if wf else "_None._\n") + "\n"

    s += "## Claude Code project skills\n\n| Skill | Description |\n|---|---|\n"
    for f in sorted(p for p in c["texts"] if p.startswith(".claude/skills/") and p.endswith("SKILL.md")):
        t = c["texts"][f]
        desc = frontmatter_field(t, "description").replace("|", "\\|")
        if len(desc) > 220:
            desc = desc[:217].rstrip() + "..."
        s += f"| `{frontmatter_field(t, 'name') or f.split('/')[2]}` | {desc} |\n"
    return s


