SOURCE_ROOTS = ("app/", "src/", "pages/", "components/", "lib/", "features/")
ASSET_ROOTS = ("public/",)


def doc_30(c) -> str:
    s = header("Codebase Inventory", "Every source file and asset group in the working tree.", c["now"])
    sizes = c["sizes"]

    s += "## Source files\n\n"
    src = [f for f in c["files"] if f.startswith(SOURCE_ROOTS)]
    if not src:
        s += "_No files under the known source roots._\n\n"
    groups: dict[str, list[str]] = defaultdict(list)
    for f in src:
        groups[f.rsplit("/", 1)[0] if "/" in f else "."].append(f)
    for d in sorted(groups):
        s += f"### `{d}/`\n\n| File | Bytes |\n|---|---|\n"
        for f in groups[d]:
            s += f"| `{f.rsplit('/', 1)[-1]}` | {sizes.get(f, 0)}{' **(empty)**' if sizes.get(f, 0) == 0 else ''} |\n"
        s += "\n"

    s += "## Static assets\n\n| Directory | Files | Extensions |\n|---|---|---|\n"
    assets: dict[str, list[str]] = defaultdict(list)
    for f in c["files"]:
        if f.startswith(ASSET_ROOTS):
            assets[f.rsplit("/", 1)[0]].append(f)
    for d in sorted(assets):
        exts = sorted({f.rsplit(".", 1)[-1].lower() for f in assets[d] if "." in f.rsplit("/", 1)[-1]})
        s += f"| `{d}/` | {len(assets[d])} | {', '.join(exts)} |\n"
    s += "\n"

    s += "## Documentation and tooling files\n\n"
    other = [f for f in c["files"]
             if not f.startswith(SOURCE_ROOTS + ASSET_ROOTS) and not f.startswith(".context/")]
    for f in other:
        s += f"- `{f}` ({sizes.get(f, 0)} B)\n"
    s += "\n"

    pkg = c["package"]
    for key in ("dependencies", "devDependencies"):
        deps = pkg.get(key) or {}
        s += f"## `{key}`\n\n"
        if not deps:
            s += "_none_\n\n"
            continue
        s += "| Package | Spec |\n|---|---|\n"
        for n in sorted(deps):
            s += f"| `{n}` | `{deps[n]}` |\n"
        s += "\n"

    s += ("## Import sites of heavy / fenced libraries\n\n"
          "Rule 5 fences Three.js/R3F out of the critical bundle. These are the files that import them\n"
          "right now:\n\n")
    if c["heavy_imports"]:
        s += "| File | Imports |\n|---|---|\n"
        for f, libs in sorted(c["heavy_imports"].items()):
            s += f"| `{f}` | {', '.join(f'`{l}`' for l in libs)} |\n"
    else:
        s += "_None._\n"
    return s


# ----------------------------------------------------------------- doc 40

def doc_40(c) -> str:
    pkg = c["package"]
    s = header("Roadmap Progress Evidence",
               "Filesystem signals per roadmap phase. Evidence only, never a completion verdict.", c["now"])
    s += ("Each phase in `docs/Roadmap.md` is listed with signals that can be checked mechanically.\n"
          "A satisfied signal means the artefact exists, **not** that the phase's acceptance criteria\n"
          "pass. Phase completion is recorded by hand in `60-decisions.md`, or verified with the\n"
          "`verify-feature` skill.\n\n")

    next_spec = dep_version(pkg, "next") or ""
    m = re.search(r"(\d+)", next_spec)
    next_major = int(m.group(1)) if m else 0
    three_outside = [f for f in c["heavy_imports"] if "/rogue/three/" not in f]

    phases = [
        ("P0 — Repository and baseline", [
            ("`docs/legacy-content/` harvest exists", has_path(c, "docs/legacy-content")),
            (f"Next.js major ≥ 15 (found `{next_spec or 'none'}`)", next_major >= 15),
            ("App Router present (`app/` or `src/app/`)", has_path(c, "app") or has_path(c, "src/app")),
            ("`tsconfig.json` present", "tsconfig.json" in c["files"]),
            ("Tailwind CSS dependency", bool(dep_version(pkg, "tailwindcss"))),
            ("Chakra UI removed", not dep_version(pkg, "@chakra-ui/react")),
            ("CI workflow under `.github/workflows/`", has_path(c, ".github/workflows")),
        ]),
        ("P1 — Domain and content model", [
            ("`src/domain/` or `src/content/` present", has_path(c, "src/domain") or has_path(c, "src/content")),
            ("Test runner dependency (vitest)", bool(dep_version(pkg, "vitest"))),
        ]),
        ("P2 — Shell and Classic Mode", [
            ("Paths mentioning `classic`", bool(paths_containing(c, "classic"))),
        ]),
        ("P3 — Mode system and synchronization", [
            ("Zustand dependency", bool(dep_version(pkg, "zustand"))),
            ("Paths mentioning `mode`", bool(paths_containing(c, "mode"))),
        ]),
        ("P4 — Card Mode static experience", [
            ("Paths mentioning `rogue`", bool(paths_containing(c, "rogue"))),
            ("`motion` dependency", bool(dep_version(pkg, "motion"))),
        ]),
        ("P5 — Lazy loading and preload", [
            ("_Not mechanically detectable — check bundle budgets in CI._", False),
        ]),
        ("P6 — Drag/drop", [
            ("`@dnd-kit/*` dependency", bool(deps_matching(pkg, "@dnd-kit/"))),
        ]),
        ("P7 — Section-specific interactions", [
            ("Paths mentioning `panel`", bool(paths_containing(c, "panel"))),
        ]),
        ("P8 — Optional 3D", [
            ("`@react-three/*` dependency", bool(deps_matching(pkg, "@react-three/"))),
            ("Three.js imported only under `*/rogue/three/`",
             bool(c["heavy_imports"]) and not three_outside),
        ]),
        ("P9 — Performance / a11y hardening", [
            ("_Not mechanically detectable._", False),
        ]),
        ("P10 — Content polish and release", [
            ("_Not mechanically detectable._", False),
        ]),
    ]
    for name, signals in phases:
        s += f"## {name}\n\n"
        for label, ok in signals:
            s += f"- [{'x' if ok else ' '}] {label}\n"
        s += "\n"

    if three_outside:
        s += ("## Rule-5 exposure\n\nThree.js / R3F is imported outside a `rogue/three/` seam:\n\n"
              + "".join(f"- `{f}`\n" for f in sorted(three_outside)) + "\n")
    return s


