"""Markdown renderers for the Manuel Ortiz Portfolio project-memory snapshot.

Every renderer is a pure function of the context dict built by
generate-context.py. Output must be deterministic for a given repository state.
"""

from __future__ import annotations

import re
from collections import defaultdict

TITLE = "Manuel Ortiz Portfolio"
AUTHORITY = "Git working tree > CLAUDE.md > docs/ > this document"


# ------------------------------------------------------------------ helpers

def header(title: str, purpose: str, now: str) -> str:
    return (
        f"# {TITLE} — {title}\n\n"
        f"<!-- generated-at: {now} -->\n"
        f"> Project-memory document. {purpose}\n"
        f"> Authority order: {AUTHORITY}.\n"
        f"> Generated by `scripts/notebooklm/generate-context.py` from repository state. Do not hand-edit.\n\n"
    )


_FENCE = re.compile(r"^\s*(```|~~~)")


def demote_headings(text: str, levels: int = 1) -> str:
    """Push every Markdown heading down so embedded docs nest under ours."""
    out: list[str] = []
    in_fence = False
    for line in text.splitlines():
        if _FENCE.match(line):
            in_fence = not in_fence
        elif not in_fence and line.startswith("#"):
            hashes = len(line) - len(line.lstrip("#"))
            if line[hashes:hashes + 1] in (" ", ""):
                line = "#" * min(hashes + levels, 6) + line[hashes:]
        out.append(line)
    return "\n".join(out).rstrip() + "\n"


def embed(c, rel: str) -> str:
    text = c["texts"].get(rel)
    if text is None:
        return f"## `{rel}`\n\n_File not present in the repository._\n\n"
    if not text.strip():
        return f"## `{rel}`\n\n_File is empty._\n\n"
    return f"## Source: `{rel}` (verbatim, headings demoted one level)\n\n{demote_headings(text)}\n"


def dep_version(pkg: dict, name: str) -> str | None:
    for key in ("dependencies", "devDependencies"):
        v = (pkg.get(key) or {}).get(name)
        if v:
            return v
    return None


def deps_matching(pkg: dict, prefix: str) -> list[str]:
    names: set[str] = set()
    for key in ("dependencies", "devDependencies"):
        names.update(n for n in (pkg.get(key) or {}) if n.startswith(prefix))
    return sorted(names)


def has_path(c, prefix: str) -> bool:
    return any(f == prefix or f.startswith(prefix.rstrip("/") + "/") for f in c["files"])


def paths_containing(c, needle: str, roots: tuple[str, ...] = ("src/", "app/", "components/")) -> list[str]:
    return [f for f in c["files"] if f.startswith(roots) and needle in f.lower()]


def stack(c) -> list[tuple[str, str]]:
    pkg = c["package"]
    router = []
    if has_path(c, "app") or has_path(c, "src/app"):
        router.append("App Router")
    if has_path(c, "pages") or has_path(c, "src/pages"):
        router.append("Pages Router")
    ts = "yes (`tsconfig.json`)" if "tsconfig.json" in c["files"] else "no — plain JavaScript"
    rows = [
        ("Next.js", dep_version(pkg, "next") or "(not a dependency)"),
        ("React", dep_version(pkg, "react") or "(not a dependency)"),
        ("Router", " + ".join(router) or "(none detected)"),
        ("TypeScript", ts),
        ("Tailwind CSS", dep_version(pkg, "tailwindcss") or "no"),
        ("Chakra UI", dep_version(pkg, "@chakra-ui/react") or "no"),
        ("Motion / framer-motion",
         " / ".join(f"`{n}` {dep_version(pkg, n)}" for n in ("motion", "framer-motion") if dep_version(pkg, n)) or "no"),
        ("Zustand", dep_version(pkg, "zustand") or "no"),
        ("dnd-kit", ", ".join(deps_matching(pkg, "@dnd-kit/")) or "no"),
        ("Three.js / R3F",
         ", ".join(n for n in ["three", *deps_matching(pkg, "@react-three/")] if dep_version(pkg, n)) or "no"),
        ("Test runner",
         ", ".join(n for n in ("vitest", "jest", "@playwright/test") if dep_version(pkg, n)) or "none"),
    ]
    return rows


def table(rows: list[tuple[str, str]], head: tuple[str, str] = ("Field", "Value")) -> str:
    s = f"| {head[0]} | {head[1]} |\n|---|---|\n"
    for k, v in rows:
        s += f"| {k} | {v} |\n"
    return s + "\n"


def frontmatter_field(text: str, field: str) -> str:
    m = re.search(rf"^{field}:\s*(.+)$", text, re.MULTILINE)
    return m.group(1).strip().strip("'\"") if m else ""


